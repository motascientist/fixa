let LANG = 'en';

function detectLang(preference) {
  if (preference === 'pt' || preference === 'en') return preference;
  const device = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  return /^pt\b/i.test(device) ? 'pt' : 'en';
}

function t(key, vars) {
  let s = STRINGS[LANG][key];
  if (s === undefined) s = STRINGS.en[key];
  if (s === undefined) return key;
  if (Array.isArray(s)) s = s[vars && vars.n === 1 ? 0 : 1];
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] !== undefined ? vars[k] : m));
}
const tn = (key, n, vars) => t(key, { ...vars, n });

const locale = () => (LANG === 'pt' ? 'pt-BR' : 'en-US');
const formatDecimal = x => x.toLocaleString(locale(), { minimumFractionDigits: 1, maximumFractionDigits: 1 });

function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}

function setLanguage(preference) {
  LANG = detectLang(preference);
  document.documentElement.lang = LANG === 'pt' ? 'pt-BR' : 'en';
  const meta = document.querySelector('meta[name=description]');
  if (meta) meta.content = t('metaDescription');
  applyI18n();
}
